#!/usr/bin/env node
/*
 * Bundle the design system into dist/ (one CSS + one JS + fonts + assets).
 *
 * Node port of build-dist.py — identical output. Use this when the system
 * Python is unavailable (e.g. /usr/bin/python3 gated behind the Xcode CLT
 * licence). Run from the repo root:  node build-dist.js
 *
 * Regenerate whenever a component's CSS/JS changes. Do not hand-edit dist/.
 */
const fs = require('fs');
const path = require('path');

const read = p => fs.readFileSync(p, 'utf8');
const stripImports = css => css.replace(/^\s*@import[^;]*;\s*$/gm, '');

// Files one level under each component dir, e.g. globComponents('.css').
function globComponents(suffix) {
  const out = [];
  for (const dir of fs.readdirSync('components')) {
    const d = path.join('components', dir);
    if (!fs.statSync(d).isDirectory()) continue;
    for (const f of fs.readdirSync(d)) {
      if (f.endsWith(suffix)) out.push(path.join(d, f));
    }
  }
  return out.sort();
}

fs.mkdirSync('dist', { recursive: true });

// ---- CSS: tokens, typography, then every component (A–Z) ----
const parts = ["/* Zego Design System — bundled stylesheet (generated by build-dist.py). Do not edit. */\n"];
const tokens = read('tokens/tokens.css').split("url('../fonts/").join("url('fonts/");
parts.push("/* ==== tokens/tokens.css ==== */\n" + tokens);
parts.push("\n/* ==== tokens/typography.css ==== */\n" + stripImports(read('tokens/typography.css')));
for (const f of globComponents('.css')) {
  const css = stripImports(read(f)).split("url('../../assets/partners/").join("url('assets/partners/");
  parts.push("\n/* ==== " + f + " ==== */\n" + css);
}
fs.writeFileSync('dist/zego-ds.css', parts.join('\n'));

// ---- JS: every component behaviour concatenated (self-init IIFEs) ----
const js = ["/* Zego Design System — bundled behaviour (generated by build-dist.py). */\n"];
for (const f of globComponents('.js')) {
  js.push("\n/* ==== " + f + " ==== */\n" + read(f));
}
fs.writeFileSync('dist/zego-ds.js', js.join('\n'));

// ---- copy fonts + assets ----
for (const d of ['fonts', 'assets']) {
  const dst = path.join('dist', d);
  fs.rmSync(dst, { recursive: true, force: true });
  if (fs.existsSync(d)) {
    fs.cpSync(d, dst, {
      recursive: true,
      filter: src => { const b = path.basename(src); return b !== '.DS_Store' && b !== 'README.md'; },
    });
  }
}

// ---- ready-to-copy HTML snippets (one per component, scaffolding stripped) ----
const titleCase = name => name.split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join(' ');
fs.mkdirSync('dist/components', { recursive: true });
for (const f of fs.readdirSync('dist/components')) if (f.endsWith('.html')) fs.rmSync(path.join('dist/components', f));

for (const demo of globComponents('-demo.html')) {
  const name = path.basename(demo).slice(0, -('-demo.html'.length));
  let b = read(demo);
  const m = b.match(/<body[^>]*>([\s\S]*)<\/body>/i);
  b = m ? m[1] : b;
  b = b.replace(/<script\b[\s\S]*?<\/script>/gi, '');
  b = b.replace(/<style\b[\s\S]*?<\/style>/gi, '');
  b = b.replace(/<span class="label">[\s\S]*?<\/span>/g, '');
  b = b.replace(/<h1\b[^>]*>[\s\S]*?<\/h1>/gi, '');
  b = b.replace(/<h2\b[^>]*>[\s\S]*?<\/h2>/gi, '');
  b = b.replace(/<p class="subtitle">[\s\S]*?<\/p>/gi, '');
  b = b.replace(/\sdata-theme=(["'])dark\1/g, '');
  if (!/[<]section\s+class=/.test(b)) b = b.replace(/<\/?section[^>]*>/gi, '');   // unwrap demo-only <section> groups
  const lines = b.split('\n');
  const indents = lines.filter(l => l.trim()).map(l => l.length - l.replace(/^\s+/, '').length);
  const cut = indents.length ? Math.min(...indents) : 0;
  b = lines.map(l => (l.length >= cut ? l.slice(cut) : l)).join('\n');
  b = b.replace(/\n[ \t]*\n[ \t]*\n+/g, '\n\n').trim();
  const header = "<!-- " + titleCase(name) + " — Zego Design System\n" +
                 "     Paste into a page that loads dist/zego-ds.css + dist/zego-ds.js. -->\n\n";
  fs.writeFileSync('dist/components/' + name + '.html', header + b + '\n');
}

const snips = fs.readdirSync('dist/components').filter(f => f.endsWith('.html')).length;
console.log(`Built dist/zego-ds.css (${fs.statSync('dist/zego-ds.css').size} bytes), ` +
            `dist/zego-ds.js (${fs.statSync('dist/zego-ds.js').size} bytes), ${snips} component snippets`);
